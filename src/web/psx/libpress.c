/* Register map: a0=bs, a1=out, a2=T+1024, a3=T+33792, v0=bit window,  */
/* v1=consumed bits, t4=qscale<<10, t5=block-in-MB (0..6),             */
/* t7/t8/t9 = Cb/Cr/Y DC predictors.                                   */

int DecDCTvlc2(u_long *bs, u_long *buf, DECDCTTAB table)
{
	const u_short *T = table;
	const u_short *src = (const u_short *)bs;
	u_short *w = (u_short *)buf;
	u_short *wlim = w + 80000; /* MOV_RUN_LEVEL_BUFFER = u_long[40960] */
	uint32_t v0, v1 = 0;
	uint32_t t0, t1, t2, t3, t4, t5 = 0, t7 = 0, t8 = 0, t9 = 0;

	/* resume a suspended decode */
	if (bs == NULL)
		return 1;

	t4 = (uint32_t)src[2] << 10;
	if ((int32_t)src[3] >= 3)
		t5 = 1;
	v0 = ((uint32_t)src[4] << 16) | src[5];
	src += 6;

	w[0] = src[-6]; /* MDEC0 command word (e.g. 0x38000540) */
	w[1] = src[-5];
	w += 2;

blockhead:
	if (t5 != 0) {
		int idx;
		const u_short *dt;
		uint32_t dc;

		t0 = v0 >> 22;
		if (t0 == 0x3FF)
			goto stream_end;
		/* DC vlc: t5<3 -> chroma table (elem 512), else luma (elem 0) */
		dt = (t5 < 3) ? T + 512 : T;
		idx = (v0 >> 24) & 0xFF;
		t1 = dt[idx * 2];
		t2 = dt[idx * 2 + 1];
		v0 <<= t1;
		v1 += t1;
		t0 = 0;
		if (t2 != 0) {
			int at = 32 - (int)t2;
			t0 = v0 >> at;
			if (!(v0 & 0x80000000)) {
				v0 <<= t2;
				t0 -= 0xFFFFFFFFu >> at;
			} else {
				v0 <<= t2;
			}
			v1 += t2;
		}
		if (v1 & 0x10) {
			v1 &= 0xF;
			v0 |= (uint32_t)(*src++) << v1;
		}
		/* DC prediction: t5=1->t7 (Cb), t5=2->t8 (Cr), else t9 (Y) */
		{
			int sel = (int)t5 - 2;
			if (sel > 0) {
				dc = t9 + t0;
				t9 += t0;
			} else if (sel == 0) {
				dc = t8 + t0;
				t8 += t0;
			} else {
				dc = t7 + t0;
				t7 += t0;
			}
			t1 = ((dc << 2) & 0x3FF) | t4;
		}
		t5++;
		if (t5 == 7)
			t5 -= 6;
		*w = (u_short)t1;
		w++;
	} else {
		/* v2 stream: raw 10-bit DC */
		t0 = v0 >> 22;
		if (t0 == 0x1FF)
			goto stream_end;
		v0 <<= 10;
		v1 += 10;
		if (v1 & 0x10) {
			v1 &= 0xF;
			v0 |= (uint32_t)(*src++) << v1;
		}
		*w++ = (u_short)(t0 | t4);
	}

acloop:
	{
		int idx = (v0 >> 19) & 0x1FFF;
		const u_short *e = T + 1024 + idx * 4;
		t1 = e[0] | ((uint32_t)e[1] << 16);
		t3 = e[2] | ((uint32_t)e[3] << 16);
		if (t1 == 0) {
			v0 <<= 8;
			v1 += 8;
			if (v1 & 0x10) {
				v1 &= 0xF;
				v0 |= (uint32_t)(*src++) << v1;
			}
			idx = (v0 >> 23) & 0x1FF;
			t1 = T[33792 + idx * 2] |
			     ((uint32_t)T[33792 + idx * 2 + 1] << 16);
			t3 = 0;
		}
		v0 <<= (t1 & 0xFF);
		v1 += t1 & 0xFF;
		if (v1 & 0x10) {
			v1 &= 0xF;
			v0 |= (uint32_t)(*src++) << v1;
		}
		t1 >>= 16;
		if (t1 == 0x7C1F)
			goto escape;
		if (t1 == 0xFE00) {
			*w++ = (u_short)t1;
			goto blockhead;
		}
		*w++ = (u_short)t1;
		if (t3 != 0) {
			t2 = t3 & 0xFFFF;
			if (t2 == 0x7C1F)
				goto escape;
			if (t2 == 0xFE00) {
				*w++ = (u_short)t2;
				goto blockhead;
			}
			*w++ = (u_short)t2;
			t2 = t3 >> 16;
			if (t2 != 0) {
				if (t2 == 0x7C1F)
					goto escape;
				if (t2 == 0xFE00) {
					*w++ = (u_short)t2;
					goto blockhead;
				}
				*w++ = (u_short)t2;
			}
		}
		goto acnext;
escape:
		*w++ = (u_short)(v0 >> 16);
		v0 <<= 16;
		v0 |= (uint32_t)(*src++) << v1;
		goto acloop;
acnext:
		if (w >= wlim)
			return 1; /* buffer full - would save state in retail */
		goto acloop;
	}

stream_end:
	{
		int i;
		for (i = 0; i < 64; i++)
			*w++ = 0xFE00;
	}
	return 0;
}

