/* zig-zag position -> natural block index */
static const uint8_t zagzig[64] = {
	 0, 1, 8,16, 9, 2, 3,10,
	17,24,32,25,18,11, 4, 5,
	12,19,26,33,40,48,41,34,
	27,20,13, 6, 7,14,21,28,
	35,42,49,56,57,50,43,36,
	29,22,15,23,30,37,44,51,
	58,59,52,45,38,31,39,46,
	53,60,61,54,47,55,62,63
};

static const u_short *mdec_src;	/* RL word source */
static long mdec_pos;		/* u16 index into mdec_src */
static int mdec_rgb24 = 1;
static void (*mdec_out_cb)(void);
static void (*mdec_in_cb)(void);


static int mdec_cb_depth, mdec_cb_pending;

static void idct8x8(int32_t *blk, int16_t *out)
{
	int64_t tmp[64];
	for (int x = 0; x < 8; x++)
		for (int y = 0; y < 8; y++) {
			int64_t s = 0;
			for (int i = 0; i < 8; i++)
				s += (int64_t)blk[x + i * 8] * mdec_scale[y + i * 8];
			tmp[x + y * 8] = s;
		}
	for (int x = 0; x < 8; x++)
		for (int y = 0; y < 8; y++) {
			int64_t s = 0;
			for (int i = 0; i < 8; i++)
				s += (int64_t)mdec_scale[x + i * 8] * tmp[i + y * 8];
			out[x + y * 8] = (int16_t)((s >> 32) + ((s >> 31) & 1));
		}
}

static int sext10(uint32_t v)
{
	return (int32_t)(v & 0x3FF) - ((v & 0x200) ? 0x400 : 0);
}

/* decode one 8x8 block (returns 0 when the RL stream is exhausted) */
static int mdec_block(int chroma, int16_t *out)
{
	uint32_t w0;
	int qs, dc, k;
	int32_t blk[64];

	if (mdec_src == NULL)
		return 0;
	w0 = mdec_src[mdec_pos++];
	if (w0 == 0xFE00)
		return 0;
	qs = (int)(w0 >> 10);
	dc = sext10(w0);
	memset((unsigned char *)blk, 0, sizeof blk);
	blk[0] = dc * (chroma ? mdec_iq_c[0] : mdec_iq_y[0]);
	k = 0;
	for (;;) {
		uint32_t wv = mdec_src[mdec_pos++];
		if (wv == 0xFE00)
			break;
		k += (int)(wv >> 10) + 1;
		if (k >= 64)
			break;
		if (sext10(wv) != 0)
			blk[zagzig[k]] = (sext10(wv) *
					  (chroma ? mdec_iq_c[k]
						  : mdec_iq_y[k]) * qs + 4) >> 3;
	}
	idct8x8(blk, out);
	return 1;
}

/* decode one macroblock: Cb, Cr, Y0..Y3 -> rgb24 into dst (16x16) */
static int mdec_macroblock(uint8_t *dst, int stride)
{
	int16_t y[4][64], cb[64], cr[64];

	if (!mdec_block(1, cr) || !mdec_block(1, cb))
		return 0;
	for (int i = 0; i < 4; i++)
		if (!mdec_block(0, y[i]))
			return 0;
	for (int py = 0; py < 16; py++)
		for (int px = 0; px < 16; px++) {
			int crv = cr[(py / 2) * 8 + px / 2];
			int cbv = cb[(py / 2) * 8 + px / 2];
			int yy = y[(px / 8) + (py / 8) * 2]
				 [(py % 8) * 8 + px % 8] + 128;
			int r = (yy * 256 + 359 * crv) >> 8;
			int g = (yy * 256 - 88 * cbv - 183 * crv) >> 8;
			int b = (yy * 256 + 454 * cbv) >> 8;
			uint8_t *d = dst + (py * stride + px) * 3;
			d[0] = r < 0 ? 0 : (r > 255 ? 255 : r);
			d[1] = g < 0 ? 0 : (g > 255 ? 255 : g);
			d[2] = b < 0 ? 0 : (b > 255 ? 255 : b);
		}
	return 1;
}

void DecDCTReset(int mode)
{
	/* retail: mode!=0 issues MDEC_reset; mode==0 resets callbacks.
	 * The game's DecDCTin mode bits select the output depth. */
	(void)mode;
	mdec_rgb24 = 1;
	mdec_src = NULL;
	mdec_pos = 0;
}

void DecDCTin(u_long *buf, int mode)
{
	/* retail patches the MDEC0 command word: mode&1 clears bit27
	 * (signed output), mode&2 sets bit25 (depth select). */
	uint32_t *w = (uint32_t *)buf;
	if (mode & 1)
		w[0] &= 0xF7FFFFFF;
	else
		w[0] |= 0x08000000;
	if (mode & 2)
		w[0] |= 0x02000000;
	else
		w[0] &= 0xFDFFFFFF;
	mdec_src = (const u_short *)buf;
	mdec_pos = 2; /* skip the u32 command word */
	mdec_rgb24 = (mode & 2) != 0;

	if (mdec_in_cb != NULL)
		mdec_in_cb();
}

void DecDCTout(u_long *buf, int size)
{
	/* size is in u_longs.  The game requests one 16-pixel column
	 * strip per call ((24*H)/2 halfwords = 16 px x H rows of RGB24). */
	uint8_t *dst = (uint8_t *)buf;
	long bytes = (long)size * 4;
	int mbs;

	if (mdec_rgb24)
		mbs = (int)(bytes / (16 * 16 * 3));
	else
		mbs = (int)(bytes / (16 * 16 * 2));
	for (int m = 0; m < mbs; m++) {
		uint8_t col[16 * 16 * 3];
		if (!mdec_macroblock(col, 16))
			memset(col, 0, sizeof col);
		if (mdec_rgb24) {
			for (int y = 0; y < 16; y++)
				memcpy(dst + ((m * 16 + y) * 16) * 3,
				       col + y * 16 * 3, 16 * 3);
		} else {
			for (int y = 0; y < 16; y++)
				for (int x = 0; x < 16; x++) {
					const uint8_t *p =
						col + (y * 16 + x) * 3;
					((uint16_t *)dst)[(m * 16 + y) * 16 + x] =
						(p[0] >> 3) |
						((p[1] >> 3) << 5) |
						((p[2] >> 3) << 10);
				}
		}
	}

	/* retail is async: the out-callback runs after the DMA, so the
	 * game's LoadImage of the previous strip interleaves with the
	 * next decode.  Defer the callback when we are nested inside a
	 * callback so nested DecDCTout() calls don't pre-decode every
	 * strip before the first LoadImage runs. */
	if (mdec_out_cb == NULL)
		return;
	if (mdec_cb_depth != 0) {
		mdec_cb_pending = 1;
		return;
	}
	do {
		mdec_cb_pending = 0;
		mdec_cb_depth++;
		mdec_out_cb();
		mdec_cb_depth--;
	} while (mdec_cb_pending && mdec_out_cb != NULL);
}

