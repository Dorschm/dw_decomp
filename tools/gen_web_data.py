#!/usr/bin/env python3
"""Extract authentic libgte lookup tables from the splat data dump
(asm/us/main/data/psyq/libgte.data.s) into a C source file.

Tables emitted (all int16_t, matching the .short elements):
  rsin_tbl    - quarter-wave sin, 1.12 fixed (rsin/rcos/sin_1/cos_1)
  SQRT        - SquareRoot0/12 normalized-sqrt table
  rcossin_tbl - 4096-entry full-circle table (unused on the buggy-build
                path but kept for completeness)
  ratan_tbl   - ratan2 angle table (index = ratio*1024 scale)
"""
import re
import sys

SRC = "asm/us/main/data/psyq/libgte.data.s"
OUT = sys.argv[1] if len(sys.argv) > 1 else None


def extract(name, text, word=False):
    m = re.search(
        r"dlabel_section\s+%s\b(.*?)enddlabel_section\s+%s" % (name, name),
        text, re.S)
    if not m:
        raise SystemExit("table %s not found" % name)
    pat = r"\.word\s+0x([0-9A-Fa-f]+)" if word else r"\.short\s+0x([0-9A-Fa-f]+)"
    return [int(w, 16) for w in re.findall(pat, m.group(1))]


def emit(f, name, vals, ctype="int16_t", fmt="0x%04X", per=8):
    f.write("const %s %s[%d] = {\n" % (ctype, name, len(vals)))
    mask = 0xFFFFFFFF if ctype == "uint32_t" else 0xFFFF
    for i in range(0, len(vals), per):
        f.write("\t" + ",".join(fmt % (v & mask) for v in vals[i:i + per]) + ",\n")
    f.write("};\n\n")


def main():
    text = open(SRC, encoding="utf-8").read()
    out = open(OUT, "w") if OUT else sys.stdout
    out.write("/* generated by tools/gen_web_data.py from %s - do not edit */\n\n" % SRC)
    out.write("#include <stdint.h>\n\n")
    for name in ("rsin_tbl", "SQRT", "ratan_tbl"):
        vals = extract(name, text)
        emit(out, "gte_" + name, vals)
        sys.stderr.write("%s: %d entries\n" % (name, len(vals)))
    vals = extract("rcossin_tbl", text, word=True)
    emit(out, "gte_rcossin_tbl", vals, ctype="uint32_t", fmt="0x%08X", per=4)
    sys.stderr.write("rcossin_tbl: %d entries\n" % len(vals))


if __name__ == "__main__":
    main()
