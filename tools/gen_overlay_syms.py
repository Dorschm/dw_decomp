#!/usr/bin/env python3
"""Generate overlay_syms.c: per-overlay tables of writable data symbols.

On retail, loadDynamicLibrary() reloads the overlay's *_REL.BIN, which
resets its initialised globals. On web the overlays are statically
linked, so src/web/host/overlay.c snapshots each overlay's .data bytes
once at startup and restores them on every overlay load. This script
produces the {addr, size} tables from llvm-nm output over each overlay's
object files.

Usage: gen_overlay_syms.py OUT nm=LLVM_NM ovr=obj1,obj2,... [ovr2=...]

Only global 'D' (initialised data) symbols are emitted: the audit showed
no overlay .bss, and the only file-scope statics are compiler-generated
constants (jump tables, string literals) that are never written.
"""
import re
import subprocess
import sys

OVERLAY_IDS = {
    'btl': 1, 'std': 2, 'fish': 3, 'evl': 4, 'kar': 5, 'vs': 6,
    'mov': 7, 'doo2': 8, 'dooa': 9, 'trn': 10, 'shop': 11, 'dget': 12,
    'trn2': 13, 'murd': 14, 'endi': 15, 'eab': 16,
}

def nm_syms(nm, obj):
    out = subprocess.run([nm, '--print-size', '--defined-only', obj],
                         capture_output=True, text=True).stdout
    for line in out.splitlines():
        parts = line.split()
        # format: [addr] size type name
        if len(parts) == 4 and re.fullmatch(r'[0-9a-fA-F]+', parts[1]):
            size, typ, name = int(parts[1], 16), parts[2], parts[3]
        elif len(parts) == 3 and re.fullmatch(r'[0-9a-fA-F]+', parts[0]):
            size, typ, name = 0, parts[1], parts[2]
        else:
            continue
        if typ == 'D' and size > 0 and re.fullmatch(r'[A-Za-z_]\w*', name):
            yield name, size

def main():
    out_path = sys.argv[1]
    nm = 'llvm-nm'
    overlays = {}
    for arg in sys.argv[2:]:
        key, _, val = arg.partition('=')
        if key == 'nm':
            nm = val
        else:
            overlays[key] = val.split(',')

    decls = []
    tables = []
    for ov in sorted(overlays, key=lambda o: OVERLAY_IDS[o]):
        syms = []
        # mov: every global is re-initialised per play by
        # MOV_initEnvironment()/DecDCTvlcBuild(), so a reset is redundant
        # -- and restoring its ~460 KB of stream/VLC buffers was observed
        # to break font/text rendering afterwards (naming screen glyphs
        # missing; root cause not yet identified). Leave it out.
        if ov == 'mov':
            overlays[ov] = []
        for obj in overlays[ov]:
            syms.extend(nm_syms(nm, obj))
        table = f'ovr_syms_{ov}'
        for name, _ in syms:
            decls.append(f'extern uint8_t {name}[];')
        rows = ''.join(f'\t{{ {n}, {s} }},\n' for n, s in syms)
        tables.append(
            f'static const OvrSym {table}[] = {{\n{rows}}};\n')

    with open(out_path, 'w') as f:
        f.write('/* generated by tools/gen_overlay_syms.py */\n')
        f.write('#include <stdint.h>\n\n')
        f.write('typedef struct { void *addr; uint32_t size; } OvrSym;\n\n')
        f.write('\n'.join(decls) + '\n\n')
        f.write('\n'.join(tables) + '\n')
        f.write('const OvrSym *const OVR_SYM_TABLES[17] = {\n\t0,\n')
        for ov in sorted(overlays, key=lambda o: OVERLAY_IDS[o]):
            f.write(f'\tovr_syms_{ov},\n')
        f.write('};\n\n')
        f.write('const uint32_t OVR_SYM_COUNTS[17] = {\n\t0,\n')
        for ov in sorted(overlays, key=lambda o: OVERLAY_IDS[o]):
            f.write(f'\tsizeof(ovr_syms_{ov}) / sizeof(ovr_syms_{ov}[0]),\n')
        f.write('};\n')

if __name__ == '__main__':
    main()
