#!/usr/bin/env python3
"""List the overlay-source symbols that the PS1 link places in the *main*
executable (address >= 0x80090000) rather than in an overlay image.

Several overlay units keep data in main (the whole US `shop` unit, the
`MAIN_D_*` symbols of std/evl/dget/trn2, ...). Retail never reloads those
on an overlay load, so the web build's per-load overlay .data reset
(src/web/host/overlay.c) must not touch them -- restoring them to their
startup values corrupts live main-exe state (it blanked all text).

Usage (one-time, after changing overlay sources; run against a generated
overlay_syms.c that was made WITHOUT the resident filter):
  tools/overlay_resident.py build/us/psx/gcc/SLUS_010.32.elf.map \
      build/us/web/generated/overlay_syms.c config/us/overlay_main_resident.txt
"""
import re
import sys

MAIN_BASE = 0x80090000

def main():
    map_path, syms_path, out_path = sys.argv[1:4]
    addr = {}
    for line in open(map_path, errors='replace'):
        m = re.match(r'\s+0x(8[0-9a-f]{7})\s+([A-Za-z_]\w*)\s*$', line)
        if m:
            addr.setdefault(m.group(2), int(m.group(1), 16))
    names = set(re.findall(r'\{ (\w+), \d+ \},', open(syms_path).read()))
    resident = sorted(n for n in names if addr.get(n, 0) >= MAIN_BASE)
    missing = sorted(n for n in names if n not in addr)
    with open(out_path, 'w') as f:
        f.write('# overlay-source symbols resident in the main exe '
                '(generated by tools/overlay_resident.py)\n')
        f.write('\n'.join(resident) + '\n')
    print(f'{len(names)} overlay symbols, {len(resident)} main-resident, '
          f'{len(missing)} not in map')

main()
